// REQ-047/046: regenerate the Markdown views of compass/spec.json (requirements.md, tests.md, handover.md, decisions.md).
// Usage: node compass/build-views.mjs           → write the files
//        node compass/build-views.mjs --check   → exit 1 if handover.md is stale (used by check-spec.mjs / CI)
import { readFileSync, writeFileSync, existsSync, realpathSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const dir = new URL('./', import.meta.url);
const read = (f) => (existsSync(new URL(f, dir)) ? readFileSync(new URL(f, dir), 'utf8') : '');
const num = (id) => Number(id.split('-')[1]);
const byId = (a, b) => num(a.id) - num(b.id);

export const isDone = (r) => r.status === 'Done';
export const isFailing = (t) => /fail/i.test(t.status || '');

export function openRequirements(spec) {
  return spec.requirements.filter((r) => !isDone(r)).sort(byId);
}

export function featureStage(spec, f) {
  // Draft requirements are not agreed yet, so a feature with only Drafts is still an Idea
  const reqs = spec.requirements.filter((r) => r.featureId === f.id && r.status !== 'Draft');
  if (!reqs.length) return 'Idea';
  return reqs.every(isDone) ? 'Released' : 'Build';
}

export const openLine = (r) => `- **${r.id}** ${r.title} — ${r.status} (${r.priority})`;
export const featureRow = (spec, f) => {
  const open = openRequirements(spec).filter((r) => r.featureId === f.id).map((r) => r.id);
  return `| ${f.id} ${f.name} | ${featureStage(spec, f)} | ${open.join(', ') || '—'} |`;
};

export function summaryLine(spec) {
  const open = openRequirements(spec).length;
  const failing = spec.tests.filter(isFailing).length;
  return `- **Requirements:** ${spec.requirements.length} (${open} not done) · **Test cases:** ${spec.tests.length} (${failing} failing)`;
}

export function renderHandover(spec, { lastRelease = 'none', date = new Date().toISOString().slice(0, 10) } = {}) {
  const testsFor = (id) => spec.tests.some((t) => t.reqIds.includes(id));
  const noTests = spec.requirements.filter((r) => r.status !== 'Draft' && !testsFor(r.id)).map((r) => r.id);
  const L = [
    '# Handover',
    '',
    `_Generated by \`node compass/build-views.mjs\` on ${date}. Source of truth: \`compass/spec.json\`. CI fails when this file is stale (REQ-047)._`,
    '',
    '## Where we are',
    '| Feature | Stage | Open requirements |',
    '|---|---|---|',
    ...(spec.features || []).map((f) => featureRow(spec, f)),
    '',
    summaryLine(spec),
    `- **Requirements without tests:** ${noTests.join(', ') || 'none'}`,
    `- **Decisions (ADR):** ${(spec.decisions || []).length}`,
    `- **Last release:** ${lastRelease}`,
    '',
    '## Next step by role',
    '| Role | Start here |',
    '|---|---|',
    '| Product Owner | Approve Draft requirements and intents; decide what is switched on in Admin → Tính năng; answer items on hold. |',
    '| Business Analyst | Refine requirements in `compass/spec.json` (or the portal); every requirement needs Given/When/Then AC and a GitHub issue. |',
    '| QA | Every requirement has a test case; automate under `tests/` (unit) and `e2e/` (Playwright). |',
    '| Developer / agent | Take an Approved or In build requirement; branch `compass/REQ-xxx-short-name`; follow AGENTS.md and compass/REVIEW.md. |',
    '| Delivery Manager | Track open PRs, CI and the independent review; plan the next release tag. |',
    '| Ops | `compass-deploy.yml` deploys only after Compass CI is green on main, smoke-tests the live site and rolls back on failure. |',
    '',
    '## Open requirements',
    ...openRequirements(spec).map(openLine),
    '',
  ];
  return L.join('\n');
}

export function renderRequirements(spec) {
  const testsFor = (id) => spec.tests.filter((t) => t.reqIds.includes(id)).map((t) => t.id).join(', ') || '—';
  const reqs = [...spec.requirements].sort(byId);
  const L = [
    '# Requirements',
    '',
    '_Generated from `spec.json`. REQ-101 and up are the baseline (features built before Compass, reconstructed 2026-11-23). Features (F-xxx) are listed in [features.md](features.md)._',
    '',
    '| ID | Title | Feature | Priority | Status | Tests |',
    '|---|---|---|---|---|---|',
    ...reqs.map((r) => `| ${r.id} | ${r.title} | ${r.featureId || '—'} | ${r.priority} | ${r.status} | ${testsFor(r.id)} |`),
    '',
  ];
  for (const r of reqs) {
    L.push(`## ${r.id} — ${r.title}`, '');
    if (r.story) L.push(r.story, '');
    if (r.intent) L.push(`Intent: [${r.intent}](../${r.intent})`, '');
    if (r.design) L.push(/^none:/i.test(r.design) ? `Design: ${r.design}` : `Design: [${r.design}](../${r.design})`, '');
    if (r.description) L.push(r.description, '');
    for (const a of r.ac) L.push('- ' + a.replaceAll('\n', ' · '));
    L.push('');
  }
  return L.join('\n');
}

export function renderTests(spec) {
  const T = [
    '# Tests',
    '',
    '_Generated from `spec.json`. Unit tests: `npm test` (tests/). UI tests: `npm run test:e2e` (e2e/, Playwright, demo mode)._',
    '',
    '| ID | Title | Requirements | Type | Status | File |',
    '|---|---|---|---|---|---|',
    ...[...spec.tests].sort(byId).map((t) => `| ${t.id} | ${t.title} | ${t.reqIds.join(', ')} | ${t.type} | ${t.status} | ${t.file || '—'} |`),
  ];
  return T.join('\n') + '\n';
}

export const ADR_FIELDS = ['id', 'date', 'title', 'status', 'context', 'decision', 'consequences'];
export const ADR_STATUSES = ['Proposed', 'Accepted', 'Superseded', 'Rejected'];

// The reconstructed baseline of the existing product (REQ-101…153) is exempt from the newer process checks
export const isBaseline = (n) => n >= 101 && n <= 153;

// REQ-038: from this requirement number on (below the REQ-101 baseline) an intent file is required
export const INTENT_REQUIRED_FROM = 51;
/** Problems with requirement → intent links. readIntent(path) returns the file text or null when missing. */
export function intentProblems(spec, readIntent) {
  const problems = [];
  for (const r of spec.requirements) {
    const n = num(r.id);
    if (!/^REQ-\d+$/.test(r.id || '')) {
      problems.push(`${r.id} is not a valid requirement id (REQ-<number>)`);
      continue;
    }
    // Only the reconstructed baseline REQ-101…153 is exempt
    if (!r.intent) {
      if (n >= INTENT_REQUIRED_FROM && !isBaseline(n)) problems.push(`${r.id} has no intent (add "intent": "compass/intent/<file>.md")`);
      continue;
    }
    if (!/^compass\/intent\/[\w.-]+\.md$/.test(r.intent)) {
      problems.push(`${r.id} intent should look like compass/intent/<file>.md`);
      continue;
    }
    const text = readIntent(r.intent);
    if (text == null) problems.push(`${r.id} points to missing ${r.intent}`);
    else if (!/^Status:\s*Approved\b/m.test(text)) problems.push(`${r.id} points to ${r.intent}, which is not Approved yet`);
    else if (!(text.split(/^## Requirements\s*$/m)[1] || '').split(/^## /m)[0].includes(r.id)) problems.push(`${r.intent} does not list ${r.id} under Requirements`);
  }
  return problems;
}

// REQ-055: from this requirement number on (below the REQ-101 baseline) a design is required before code
export const DESIGN_REQUIRED_FROM = 52;
/** REQ-057: from this requirement on, a UI design file must link at least one Figma frame */
export const FIGMA_REQUIRED_FROM = 56;
/** a frame link in the project's Figma file (spec.designTool); any Figma file when designTool is not set */
const figmaFrame = (text, designTool) => {
  const key = /figma\.com\/design\/([0-9A-Za-z]{22,128})/.exec(designTool || '')?.[1] || '[0-9A-Za-z]{22,128}';
  return new RegExp(`https://(www\\.)?figma\\.com/design/${key}[^\\s)]*[?&]node-id=\\d+-\\d+`).test(text);
};
/**
 * Problems with requirement → design links. A requirement has "design": "compass/design/<file>.md" or
 * "design": "none: <reason>" (no UI). In build / Done needs an Approved design file that lists the requirement.
 */
export function designProblems(spec, readDesign) {
  const problems = [];
  for (const r of spec.requirements) {
    const n = num(r.id);
    if (!r.design) {
      if (n >= DESIGN_REQUIRED_FROM && !isBaseline(n) && r.status !== 'Draft') problems.push(`${r.id} has no design (add "design": "compass/design/<file>.md", or "none: <reason>" when it has no UI)`);
      continue;
    }
    if (/^none:\s*\S/i.test(r.design)) continue;
    if (!/^compass\/design\/[\w.-]+\.md$/.test(r.design)) {
      problems.push(`${r.id} design should look like compass/design/<file>.md or "none: <reason>"`);
      continue;
    }
    const text = readDesign(r.design);
    if (text == null) problems.push(`${r.id} points to missing ${r.design}`);
    // whole id only: REQ-100 must not match inside REQ-1000
    else if (!new RegExp(`\\b${r.id}(?!\\d)`).test(text)) problems.push(`${r.design} does not mention ${r.id}`);
    else if ((r.status === 'In build' || r.status === 'Done') && !/^Status:\s*Approved\b/m.test(text)) problems.push(`${r.id} is ${r.status} but ${r.design} is not Approved — no code before the design is approved`);
    else if (n >= FIGMA_REQUIRED_FROM && !isBaseline(n) && (r.status === 'In build' || r.status === 'Done') && !figmaFrame(text, spec.designTool)) problems.push(`${r.id} is ${r.status} but ${r.design} links no Figma frame of ${spec.designTool || 'the project Figma file'} (…?node-id=…) — draw it in Figma and get it approved (REQ-057)`);
  }
  return problems;
}

// REQ-054: intents of new requirements keep the Product Owner's business need next to the revised business intent
export const NEED_REQUIRED_FROM = 52;
// REQ-059: from here on an intent also says what will be true when the change is done
export const DONE_WHEN_REQUIRED_FROM = 59;
export function needProblems(spec, readIntent) {
  const problems = [];
  const seen = new Set();
  for (const r of spec.requirements) {
    const n = num(r.id);
    if (!r.intent || n < NEED_REQUIRED_FROM || isBaseline(n) || seen.has(r.intent)) continue;
    seen.add(r.intent);
    const text = readIntent(r.intent);
    if (text == null) continue;
    const missing = [];
    if (!/^## Business need\s*$/m.test(text)) missing.push(`"## Business need" section (the Product Owner's words, revised into the business intent under "## What we want")`);
    if (n >= DONE_WHEN_REQUIRED_FROM && !/^## Done when\s*$/m.test(text)) missing.push(`"## Done when" section (what will be true when the change is done, REQ-059)`);
    if (missing.length) problems.push(`${r.intent} has no ${missing.join(' and no ')}`);
  }
  return problems;
}

/** Problems in the ADR list (REQ-046). */
export function decisionProblems(spec) {
  const problems = [];
  const reqIds = new Set(spec.requirements.map((r) => r.id));
  const seen = new Set();
  for (const a of spec.decisions || []) {
    for (const f of ADR_FIELDS) if (!a[f]) problems.push(`${a.id || '(no id)'} has no ${f}`);
    if (a.id && !/^ADR-\d{3}$/.test(a.id)) problems.push(`${a.id} should look like ADR-001`);
    if (a.date && !/^\d{4}-\d{2}-\d{2}$/.test(a.date)) problems.push(`${a.id} date should be YYYY-MM-DD`);
    if (a.reqIds !== undefined && !Array.isArray(a.reqIds)) problems.push(`${a.id} reqIds should be a list`);
    if (seen.has(a.id)) problems.push(`${a.id} is used twice`);
    seen.add(a.id);
    if (a.status && !ADR_STATUSES.includes(a.status)) problems.push(`${a.id} status must be one of ${ADR_STATUSES.join(', ')}`);
    for (const id of Array.isArray(a.reqIds) ? a.reqIds : []) if (!reqIds.has(id)) problems.push(`${a.id} references unknown ${id}`);
  }
  return problems;
}

export function renderDecisions(spec) {
  // Entries without a valid id are reported by decisionProblems; skip them here instead of crashing
  const list = (spec.decisions || []).filter((a) => /^ADR-\d{3}$/.test(a.id || '')).sort(byId);
  const L = ['# Decisions (ADR log)', '', '_Generated from `spec.json` → `decisions`. Add an ADR in the same PR whenever a decision is made in chat (REQ-046)._', ''];
  if (!list.length) return [...L, '_No decisions recorded yet._', ''].join('\n');
  L.push('| ID | Date | Decision | Status | Requirements |', '|---|---|---|---|---|');
  const reqs = (a) => (Array.isArray(a.reqIds) ? a.reqIds : []);
  for (const a of list) L.push(`| ${a.id} | ${a.date} | ${a.title} | ${a.status} | ${reqs(a).join(', ') || '—'} |`);
  L.push('');
  for (const a of list) {
    L.push(`## ${a.id} — ${a.title}`, '', `**Status:** ${a.status} · **Date:** ${a.date}${reqs(a).length ? ` · **Requirements:** ${reqs(a).join(', ')}` : ''}`, '');
    L.push(`**Context.** ${a.context}`, '', `**Decision.** ${a.decision}`, '', `**Consequences.** ${a.consequences}`, '');
  }
  return L.join('\n');
}

/** Problems that make handover.md stale (compares facts, not the generation date or wording). */
export function handoverProblems(spec, text) {
  const problems = [];
  if (!text.includes(summaryLine(spec))) problems.push(`summary line should be: ${summaryLine(spec)}`);
  const section = text.split('## Open requirements')[1] || '';
  const listed = new Set([...section.matchAll(/\*\*(REQ-\d+)\*\*/g)].map((m) => m[1]));
  const open = new Set(openRequirements(spec).map((r) => r.id));
  for (const id of open) if (!listed.has(id)) problems.push(`${id} is open but not listed`);
  for (const id of listed) if (!open.has(id)) problems.push(`${id} is listed as open but is Done or unknown`);
  // Status, title and priority of each open requirement, and the feature table, must match too
  for (const r of openRequirements(spec)) if (listed.has(r.id) && !section.includes(openLine(r))) problems.push(`${r.id} line should be: ${openLine(r)}`);
  for (const f of spec.features || []) if (!text.includes(featureRow(spec, f))) problems.push(`feature row should be: ${featureRow(spec, f)}`);
  return problems;
}

function lastTag() {
  try {
    return execFileSync('git', ['describe', '--tags', '--abbrev=0'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return 'none';
  }
}

const real = (p) => {
  try {
    return realpathSync(p);
  } catch {
    return resolve(p);
  }
};
// Run the CLI only when this file is the entry script (not when imported by check-spec or tests)
if (process.argv[1] && real(process.argv[1]) === real(fileURLToPath(import.meta.url))) {
  const spec = JSON.parse(read('spec.json'));
  if (process.argv.includes('--check')) {
    const text = read('handover.md');
    const problems = text ? handoverProblems(spec, text) : ['compass/handover.md is missing'];
    if (problems.length) {
      console.error('compass/handover.md is stale — run `node compass/build-views.mjs`:\n- ' + problems.join('\n- '));
      process.exit(1);
    }
    console.log('Handover OK');
  } else {
    writeFileSync(new URL('requirements.md', dir), renderRequirements(spec));
    writeFileSync(new URL('tests.md', dir), renderTests(spec));
    writeFileSync(new URL('handover.md', dir), renderHandover(spec, { lastRelease: lastTag() }));
    writeFileSync(new URL('decisions.md', dir), renderDecisions(spec));
    console.log('Wrote compass/requirements.md, tests.md, handover.md, decisions.md');
  }
}
