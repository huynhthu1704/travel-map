// REQ-011: tiếng Anh nằm ở file riêng, chỉ tải khi người dùng chọn English
let enPromise = null;
export function loadLangDict(lang) {
  if (lang !== 'en' || DICT.en) return Promise.resolve();
  enPromise ||= import('./i18n-en.js').then((m) => {
    DICT.en = m.default;
  });
  return enPromise;
}

export function translate(key, vars) {
  const lang = getLang();
  let s = DICT[lang]?.[key] ?? DICT.vi[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

const Ctx = createContext({ lang: 'vi', t: translate, setLang: () => {} });
export const useI18n = () => useContext(Ctx);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(getLang());
  const setLang = useCallback((l) => {
    // Đổi sang English: tải từ điển trước rồi mới đổi, để không bị lẫn chữ Việt
    loadLangDict(l).then(() => {
      setLangValue(l);
      setLangState(l);
    });
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.title = translate('app.seoTitle');
  }, [lang]);
  // `t` changes identity when the language changes, so memoised views re-render
  const t = useCallback((key, vars) => translate(key, vars), [lang]); // eslint-disable-line react-hooks/exhaustive-deps
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

